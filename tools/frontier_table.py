"""Write discover/frontier-table.json, one row per matrix of the current frontier, for the
Discovery@Home record table (discover/frontier.json). --check fails if the file is stale."""
from pathlib import Path
import sys,json
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'src'));from submissions import catalog
SOURCES={'candidate':'author-run round 2 search','baseline':'baseline ordering (AMD, RCM or METIS)','restarts':'author-run METIS restarts',
 'empirical qualification':'author-run empirical qualification','verified donor rehearsal submission against v001':'author-run donor rehearsal (seed 2301)'}
def rows():
 c,h=catalog();out=[]
 for x in c['instances']:
  out.append({'matrix_id':x['matrix_id'],'family':x['family'],'origin':x['origin'],'n':x['n'],'factor_nnz':x['score'][0],'squared_column_sum':x['score'][1],
   'max_column':x['score'][2],'order':x['frontier'],'by':SOURCES.get(x['ordering_source'],x['ordering_source']),'source':x['inherited_from']})
 return {'frontier_version':c['version'],'catalog_sha256':h,'note':'Generated by tools/frontier_table.py from the current catalog; do not edit by hand.','rows':out}
path=ROOT/'discover/frontier-table.json';text=json.dumps(rows(),indent=1)+'\n'
if sys.argv[1:]==['--check']:
 assert path.exists() and path.read_text()==text,'discover/frontier-table.json is stale: run tools/frontier_table.py';print('Frontier table matches the current catalog.')
else:
 path.write_text(text);print(f'Wrote {path.relative_to(ROOT)}')
